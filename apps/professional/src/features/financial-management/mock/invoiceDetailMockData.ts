export function getInvoiceDetailById(id: string): InvoiceDetailData {
	if (MOCK_INVOICE_DETAILS[id]) {
		return JSON.parse(JSON.stringify(MOCK_INVOICE_DETAILS[id]));
	}

	// Dynamic fallback for any invoice ID (e.g. from invoice list)
	const cleanNo = id.replace(/[^0-9]/g, "") || "4563";
	const defaultCopy = JSON.parse(JSON.stringify(MOCK_INVOICE_DETAILS["inv-1001"]));
	defaultCopy.id = id;
	defaultCopy.invoiceNo = cleanNo;
	defaultCopy.ocr = `${cleanNo}456301`;
	return defaultCopy;
}
