        "group-data-[variant=line]/tabs-list:h-[36px] group-data-[variant=line]/tabs-list:px-3 group-data-[variant=line]/tabs-list:sm:px-4.5 group-data-[variant=line]/tabs-list:pb-2 group-data-[variant=line]/tabs-list:pt-1 group-data-[variant=line]/tabs-list:font-sans group-data-[variant=line]/tabs-list:text-sm group-data-[variant=line]/tabs-list:font-semibold group-data-[variant=line]/tabs-list:leading-none group-data-[variant=line]/tabs-list:tracking-normal group-data-[variant=line]/tabs-list:text-center group-data-[variant=line]/tabs-list:rounded-none group-data-[variant=line]/tabs-list:text-slate-500 group-data-[variant=line]/tabs-list:hover:text-slate-900 group-data-[variant=line]/tabs-list:bg-transparent group-data-[variant=line]/tabs-list:data-[state=active]:bg-transparent dark:group-data-[variant=line]/tabs-list:data-[state=active]:border-transparent dark:group-data-[variant=line]/tabs-list:data-[state=active]:bg-transparent",
